/**
 * Downloads a subset of Noto Sans SC (SIL Open Font License) covering every CJK
 * character the site uses: the Chinese UI strings, substance names and all element names, including
 * the new element characters (鿫, 鿬, 鿭, 𬬻…) that many system fonts lack.
 *
 * Google Fonts subsets at most about 800 characters per request and silently returns the whole
 * font beyond that, so the characters go in parts, each a file of its own:
 *
 * - static/fonts/noto-sans-sc-{400,700}-{n}.woff2: web fallback for Chinese text
 * - src/lib/fonts/noto-sans-sc.css: their @font-face rules, each part with its own unicode-range
 * - src/lib/server/fonts/noto-sans-sc-700-{n}.ttf: for Open Graph images (Satori reads TTF, not WOFF2)
 *
 * Run after changing Chinese text: npm run fonts
 */
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const CJK = /[⺀-鿿豈-﫿＀-￯]|[\u{20000}-\u{3FFFF}]/gu;
const PART = 500;

const sources = [
	readFileSync(new URL('src/lib/i18n/locales/zh.ts', root), 'utf8'),
	readFileSync(new URL('src/lib/compounds.ts', root), 'utf8'),
	readFileSync(new URL('src/lib/data/elements.json', root), 'utf8')
];
const chars = [...new Set(sources.join('').match(CJK) ?? [])];
const parts = Array.from({ length: Math.ceil(chars.length / PART) }, (_, i) =>
	chars.slice(i * PART, (i + 1) * PART).join('')
);

/** Google Fonts serves WOFF2 to modern browsers and TTF to user agents it does not recognise. */
async function download(text: string, weight: number, format: 'woff2' | 'ttf') {
	const css = await (
		await fetch(
			`https://fonts.googleapis.com/css2?family=Noto+Sans+SC:wght@${weight}&text=${encodeURIComponent(text)}`,
			{
				headers: {
					'User-Agent':
						format === 'woff2'
							? 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120 Safari/537.36'
							: 'Mozilla/4.0'
				}
			}
		)
	).text();
	const url = css.match(/src: url\(([^)]+)\)/)?.[1];
	// A subset comes from /l/font?kit=…; anything else is the whole font, split by script.
	if (!url?.includes('/l/font?kit=')) throw new Error(`No subset for ${weight} ${format}:\n${css.slice(0, 500)}`);
	const range = css.match(/unicode-range: ([^;]+);/)?.[1] ?? null;
	return { data: Buffer.from(await (await fetch(url)).arrayBuffer()), range };
}

const dirs = { web: new URL('static/fonts/', root), og: new URL('src/lib/server/fonts/', root) };
for (const dir of Object.values(dirs)) {
	mkdirSync(dir, { recursive: true });
	for (const f of readdirSync(dir)) if (f.startsWith('noto-sans-sc-')) rmSync(new URL(f, dir));
}

const rules: string[] = [];
for (const weight of [400, 700]) {
	for (const [i, text] of parts.entries()) {
		const file = `noto-sans-sc-${weight}-${i + 1}.woff2`;
		const { data, range } = await download(text, weight, 'woff2');
		if (!range) throw new Error(`No unicode-range for ${file}`);
		writeFileSync(new URL(file, dirs.web), data);
		rules.push(`@font-face {
	font-family: 'Noto Sans SC Subset';
	src: url('/fonts/${file}') format('woff2');
	font-weight: ${weight === 400 ? '400' : '600 700'};
	font-display: swap;
	unicode-range: ${range};
}`);
	}
}
for (const [i, text] of parts.entries()) {
	writeFileSync(new URL(`noto-sans-sc-700-${i + 1}.ttf`, dirs.og), (await download(text, 700, 'ttf')).data);
}

mkdirSync(new URL('src/lib/fonts/', root), { recursive: true });
writeFileSync(
	new URL('src/lib/fonts/noto-sans-sc.css', root),
	`/*
 * Subset of Noto Sans SC (OFL) with every CJK character the site uses, including new element
 * characters most system fonts lack. Generated by \`npm run fonts\`: do not edit.
 */
${rules.join('\n\n')}
`
);

console.log(`Subset of ${chars.length} CJK characters written in ${parts.length} parts.`);
